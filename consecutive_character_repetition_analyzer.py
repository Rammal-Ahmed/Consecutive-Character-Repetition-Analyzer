# CONSECUTIVE CHARACTER REPETITION ANALYZER
#------------------------------------------------------------

samples = ["aabbbcc", "xxyy", "mississippi", "abc"]

for i in samples:
    longest = i[0]
    current = i[0]

    for ch in range(1, len(i)):
        if i[ch] == i[ch - 1]:
            current = current + i[ch]
        else:
            current = i[ch]

        if len(current) > len(longest):
           longest = current

    print(longest, "(" + str(len(longest)) + ")")